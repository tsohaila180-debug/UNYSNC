  function summarizeEmail(email, langCode) {
    const str = getStrings(langCode);
    const firstSentence = email.fullBody.split("\n").map((s) => s.trim()).find((s) => s.length > 25) || email.subject;
    const prioMap = {
      CRITICAL: str.priorityCritical,
      HIGH: str.priorityHigh,
      NORMAL: str.priorityNormal,
      LOW: str.priorityLow
    };
    const keyPoint = langCode === "ar" ? getAdaptedEmail(email, "ar").subject : firstSentence;
    return `• ${str.summaryCourseLabel}: ${email.courseTag} (${prioMap[email.priority] || email.priority})\n• ${str.summaryKeyPointLabel}: ${keyPoint}\n• ${str.summaryActionLine}`;
  }

  function generateSmartReply(email, tone, role, senderName, langCode) {
    const str = getStrings(langCode);
    const targetName = langCode === "ar" ? (email.senderNameAr || email.senderName) : email.senderName;
    const greetingTpl = role === "instructor" ? str.replyGreetingInstructor : str.replyGreetingStudent;
    const greeting = greetingTpl.replace("{name}", targetName);
    const bodyTpl = tone === "CONCISE"
      ? str.replyBodyConcise
      : tone === "SUPPORTIVE"
        ? str.replyBodySupportive
        : str.replyBodyFormal;
    const body = bodyTpl.replace("{course}", email.courseTag);
    return `${greeting}\n\n${body}\n\n${str.replyClosing}\n${senderName}`;
  }

  function extractDates(email, langCode) {
    const str = getStrings(langCode);
    const matches = [];
    const regex = /\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\s+\d{1,2}(?:,\s*\d{4})?/gi;
    let m;
    while ((m = regex.exec(email.fullBody)) !== null && matches.length < 3) {
      matches.push({
        title: str.calendarMilestoneSuffix.replace("{course}", email.courseTag),
        courseCode: email.courseTag,
        dateLabel: m[0],
        category: "assignment"
      });
    }
    if (!matches.length) {
      matches.push({
        title: str.calendarFollowUpSuffix.replace("{course}", email.courseTag),
        courseCode: email.courseTag,
        dateLabel: str.upcomingLabel,
        category: "assignment"
      });
    }
    return matches;
  }

